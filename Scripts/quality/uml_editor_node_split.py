"""UML class diagram for proposal P1 (Alexia): splitting EditorNode into a coordinator plus three
classes. Drawn by hand from editor/editor_node.h/.cpp at 57277407 and Scripts/work/after-split.patch
(all three classes are implemented there, generated by Scripts/work/make_split_patch.py).

Usage:  python uml_editor_node_split.py [OUT_PNG]
Output: out/figures/fig_P1_editor_node_split.png
"""
import os, sys
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, Rectangle

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "out", "figures", "fig_P1_editor_node_split.png")

FONT = dict(family="DejaVu Sans Mono", size=8)
LINE_H = 0.22


def uml_class(ax, x, y, w, name, methods, stereotype=None, dashed=False, fill="#ffffff"):
    """Draws a class box with a name compartment and an operations compartment; returns its anchors."""
    title = ([f"«{stereotype}»"] if stereotype else []) + [name]
    h_title = LINE_H * len(title) + 0.12
    h_ops = LINE_H * len(methods) + 0.12
    style = dict(linewidth=1.2, edgecolor="#222222", linestyle="--" if dashed else "-")
    ax.add_patch(Rectangle((x, y - h_title), w, h_title, facecolor=fill, **style))
    ax.add_patch(Rectangle((x, y - h_title - h_ops), w, h_ops, facecolor="#ffffff", **style))
    for i, t in enumerate(title):
        ax.text(x + w / 2, y - 0.08 - LINE_H * (i + 0.5), t, ha="center", va="center",
                fontweight="bold" if t == name else "normal", **FONT)
    for i, m in enumerate(methods):
        ax.text(x + 0.08, y - h_title - 0.08 - LINE_H * (i + 0.5), m, ha="left", va="center", **FONT)
    bottom = y - h_title - h_ops
    return {"top": (x + w / 2, y), "bottom": (x + w / 2, bottom), "left": (x, (y + bottom) / 2),
            "right": (x + w, (y + bottom) / 2)}


def arrow(ax, a, b, dashed=True, label=None):
    """UML dependency: dashed line with an open arrowhead."""
    ax.add_patch(FancyArrowPatch(a, b, arrowstyle="->", mutation_scale=12, linewidth=1,
                                 linestyle="--" if dashed else "-", color="#222222"))
    if label:
        ax.text((a[0] + b[0]) / 2, (a[1] + b[1]) / 2 + 0.08, label, ha="center", va="bottom",
                fontsize=7, style="italic", color="#444444")


fig, ax = plt.subplots(figsize=(13.4, 6.6))
ax.set_xlim(0, 19.0); ax.set_ylim(0.6, 8.6); ax.axis("off")

coord = uml_class(ax, 6.2, 8.4, 6.2, "EditorNode", [
    "+ _menu_option_confirm(option, confirmed)",
    "+ _set_current_scene_nocheck(idx, ignore_state)",
    "+ reload_instances_with_path_in_edited_scenes()",
    "  (each now forwards to one class below)",
], stereotype="Coordinator", fill="#e8eef7")

menu = uml_class(ax, 0.2, 5.3, 5.4, "EditorMenuActionHandler", [
    "+ _menu_option_confirm(option, confirmed)",
    "- _next_unsaved_scene()",
    "- _quick_opened()",
    "- _setup_android_build()",
    "- show_save_accept()",
], stereotype="implemented in demo patch", fill="#e9f5e9")
scene = uml_class(ax, 5.9, 5.3, 5.8, "EditorSceneManager", [
    "+ _set_current_scene_nocheck(idx, ignore_state)",
    "- _set_main_scene_state()",
], stereotype="implemented in demo patch", fill="#e9f5e9")
reload_ = uml_class(ax, 12.0, 5.3, 6.8, "EditorSceneReloader", [
    "+ reload_instances_with_path_in_edited_scenes()",
    "- update_node_from_node_modification_entry()",
    "- replace_history_reimported_nodes()",
    "- get_scene_editor_data_for_node()",
    "- _notify_nodes_scene_reimported()",
    "- _remove_all_not_owned_children()",
], stereotype="implemented in demo patch", fill="#e9f5e9")

for box in (menu, scene, reload_):
    arrow(ax, coord["bottom"], box["top"], label="delegates to")

deps = [("EditorData", 1.8), ("SceneTreeDock", 6.2), ("EditorSelection", 10.6), ("EditorUndoRedoManager", 15.0)]
dep_boxes = {n: uml_class(ax, x, 1.45, 3.2, n, [], fill="#f4f4f4") for n, x in deps}
for n in ("EditorData", "SceneTreeDock"):
    arrow(ax, scene["bottom"], dep_boxes[n]["top"])
for n in ("EditorData", "SceneTreeDock", "EditorSelection", "EditorUndoRedoManager"):
    arrow(ax, reload_["bottom"], dep_boxes[n]["top"])
arrow(ax, menu["bottom"], dep_boxes["EditorData"]["top"])
# Back-reference: the moved code reads editor state via EditorNode::get_singleton() (friend access).
arrow(ax, (reload_["top"][0] + 1.6, reload_["top"][1]), coord["right"])
ax.text(15.9, 6.85, "all three use EditorNode::get_singleton()\n(back-reference, friend access)", fontsize=7,
        style="italic", color="#444444", ha="center")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
fig.savefig(OUT, dpi=200, bbox_inches="tight", facecolor="white")
print("[uml] ->", OUT)

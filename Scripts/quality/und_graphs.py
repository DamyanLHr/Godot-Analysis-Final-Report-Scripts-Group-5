"""Exports the Understand figures used in the report to PNG. Each one is the same view you get in
the Understand GUI, so it can be regenerated by script or re-made by hand.

Usage (Understand's bundled interpreter; one figure per process, because Understand 1264's Python
API crashes when two treemaps are exported in the same process):
  for f in $(upython und_graphs.py --list); do upython und_graphs.py <db.und> <out_dir> $f; done
Tool:  SciTools Understand build 1264 (understand.version() == 8.0.1264)
"""
import os
import sys

import understand

# name: (kind, target, graph or treemap metrics, variant / entity type)
FIGURES = {
    # M1: where complexity sits, files grouped by folder; size = code lines, colour = deepest nesting
    "fig_M1_treemap_nesting": ("treemap", "Directory Structure", ("CountLineCode", "MaxNesting"), "file"),
    # M1: the interim's nested loops as a control-flow graph
    "fig_M1_cfg_EditorLog_rebuild_log": ("function", "EditorLog::_rebuild_log", "Control Flow", "Classic"),
    # M2: classes; size = declared methods, colour = coupled classes (EditorNode stands out)
    "fig_M2_treemap_class_coupling": ("treemap", "Directory Structure", ("CountDeclMethod", "CountClassCoupled"), "class"),
    # M3: what each lower layer depends on (edge labels = number of dependencies)
    "fig_M3_core_depends_on": ("arch", "Directory Structure/core", "Dependencies", "Depends On"),
    "fig_M3_servers_depends_on": ("arch", "Directory Structure/servers", "Dependencies", "Depends On"),
    "fig_M3_scene_depends_on": ("arch", "Directory Structure/scene", "Dependencies", "Depends On"),
    # M5: what the tests depend on (the editor barely appears)
    "fig_M5_tests_depends_on": ("arch", "Directory Structure/tests", "Dependencies", "Depends On"),
}


def main():
    if sys.argv[1] == "--list":
        print(" ".join(FIGURES))
        return
    db = understand.open(sys.argv[1])
    out, name = sys.argv[2], sys.argv[3]
    os.makedirs(out, exist_ok=True)
    kind, target, graph, extra = FIGURES[name]
    path = os.path.join(out, name + ".png")
    if kind == "treemap":
        db.metrics_treemap(path, graph[0], graph[1], extra, db.lookup_arch(target))
    elif kind == "arch":
        db.lookup_arch(target).draw(graph, path, None, extra)
    else:
        next(e for e in db.ents(kind) if e.longname() == target).draw(graph, path, None, extra)
    print(f"[und_graphs] {path}")


if __name__ == "__main__":
    main()
